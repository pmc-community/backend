import {
    readdirSync,
    statSync,
    writeFileSync,
    readFileSync,
    existsSync,
} from 'node:fs';
import { join, relative, sep } from 'node:path';

const ROUTES_DIR = join(process.cwd(), 'src/routes');
const OUTPUT_FILE = join(process.cwd(), 'src/routes.generated.ts');
const IGNORE_FILE = join(process.cwd(), '.routeignore');

/**
 * Filenames that mean "this file IS the route for its containing folder" —
 * don't add a segment for them.
 */
const INDEX_FILENAMES = new Set([
    'route.ts',
    'route.tsx',
    'index.ts',
    'index.tsx',
]);

/**
 * Fallback exceptions used only if .routeignore doesn't exist.
 */
const DEFAULT_EXCEPTIONS: string[] = [
    'schema.ts',
    'schema.tsx',
    'types.ts',
    'types.tsx',
    'utils.ts',
    'utils.tsx',
    'helpers.ts',
    'helpers.tsx',
    '__tests__',
    '*.test.ts',
    '*.test.tsx',
    '*.spec.ts',
    '*.spec.tsx',
];

function globToRegExp(pattern: string): RegExp {
    const escaped = pattern
        .replace(/[.+^${}()|[\]\\]/g, '\\$&')
        .replace(/\*/g, '.*');

    return new RegExp(`^${escaped}$`);
}

function loadExceptions(): (string | RegExp)[] {
    if (!existsSync(IGNORE_FILE)) {
        console.warn(
            '[generate-routes] No .routeignore found, using default exceptions',
        );

        return DEFAULT_EXCEPTIONS.map((p) =>
            p.includes('*') ? globToRegExp(p) : p,
        );
    }

    const lines = readFileSync(IGNORE_FILE, 'utf-8')
        .split('\n')
        .map((l) => l.trim())
        .filter((l) => l.length > 0 && !l.startsWith('#'));

    return lines.map((line) =>
        line.includes('*') ? globToRegExp(line) : line,
    );
}

const EXCEPTIONS = loadExceptions();

function isExcluded(name: string): boolean {
    return EXCEPTIONS.some((p) =>
        typeof p === 'string' ? p === name : p.test(name),
    );
}

function walk(dir: string): string[] {
    let files: string[] = [];

    for (const entry of readdirSync(dir)) {
        if (isExcluded(entry)) continue;

        const full = join(dir, entry);

        if (statSync(full).isDirectory()) {
            files = files.concat(walk(full));
        } else if (entry.endsWith('.ts') || entry.endsWith('.tsx')) {
            files.push(full);
        }
    }

    return files;
}

/**
 * '[user]'    -> ':user'
 * '[...slug]' -> ':slug{.+}'
 * 'users'     -> 'users'
 */
function toPathSegment(segment: string): string {
    const catchAll = segment.match(/^\[\.\.\.(.+)\]$/);

    if (catchAll) return `:${catchAll[1]}{.+}`;

    const dynamic = segment.match(/^\[(.+)\]$/);

    if (dynamic) return `:${dynamic[1]}`;

    return segment;
}

function toRoutePath(filePath: string): string {
    const rel = relative(ROUTES_DIR, filePath);
    const parts = rel.split(sep);

    const filename = parts[parts.length - 1];
    const dirSegments = parts.slice(0, -1);

    const segments = INDEX_FILENAMES.has(filename)
        ? dirSegments
        : [
              ...dirSegments,
              filename.replace(/\.(tsx|ts)$/, ''),
          ];

    const pathSegments = segments.map(toPathSegment);

    return pathSegments.length ? `/${pathSegments.join('/')}` : '/';
}

function toImportPath(filePath: string): string {
    const rel = relative(join(process.cwd(), 'src'), filePath)
        .replace(/\\/g, '/')
        .replace(/\.(tsx|ts)$/, '');

    return `./${rel}`;
}

function specificityScore(route: string): number {
    return route.split('/').filter((s) => s.startsWith(':')).length;
}

let files = walk(ROUTES_DIR);

files = files
    .map((file) => ({
        file,
        route: toRoutePath(file),
    }))
    .sort((a, b) => {
        const scoreDiff =
            specificityScore(a.route) -
            specificityScore(b.route);

        return scoreDiff !== 0
            ? scoreDiff
            : a.route.localeCompare(b.route);
    })
    .map((entry) => entry.file);

const imports = files
    .map(
        (f, i) =>
            `import route${i} from '${toImportPath(f)}';`,
    )
    .join('\n');

const entries = files
    .map((f) => {
        const route = toRoutePath(f);
        const importPath = toImportPath(f);

        return `  { route: ${JSON.stringify(route)}, load: () => import('${importPath}').then(m => m.default) },`;
    })
    .join('\n');

const output = `// AUTO-GENERATED by scripts/generate-routes.ts — do not edit by hand.

import type { RouteDefinition } from './types/route';

export interface RouteManifestEntry {
  route: string;
  load: () => Promise<RouteDefinition>;
}

export const routeManifest: RouteManifestEntry[] = [
${entries}
];

`;

writeFileSync(OUTPUT_FILE, output, 'utf-8');

console.log(
    `[generate-routes] Wrote ${files.length} route(s) to ${OUTPUT_FILE}`,
);
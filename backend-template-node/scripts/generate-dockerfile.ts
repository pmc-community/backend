// scripts/generate-dockerfile.ts
//
// Generates a Dockerfile (+ .dockerignore) that packages an ALREADY BUILT dist/
// folder (run "npm run build" first) into an Ubuntu based, non-root container.
//
// Usage (from the project root):
//   npx tsx scripts/generate-dockerfile.ts [options]
//
// Options:
//   --node <major>       Node.js major version        (default: build.ts target, else 22)
//   --ubuntu <version>   Ubuntu base image tag        (default: 24.04)
//   --port <number>      Port the server listens on   (default: 3000)
//   --exclude-secrets    Keep dist/.env, dist/*.pem and dist/keystore*.json OUT of the image
//                        (mount them at runtime instead)
//   --out <dir>          Where to write the files     (default: project root)
//   --force              Overwrite existing Dockerfile / .dockerignore

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';

const { values: args } = parseArgs({
    options: {
        node: { type: 'string' },
        ubuntu: { type: 'string', default: '24.04' },
        port: { type: 'string', default: '3000' },
        'exclude-secrets': { type: 'boolean', default: false },
        out: { type: 'string', default: '.' },
        force: { type: 'boolean', default: false },
    },
});

const root = process.cwd();
const outDir = resolve(root, args.out as string);

// ------------------------------------------------------------
// Inspect the project
// ------------------------------------------------------------

const pkgPath = join(root, 'package.json');
if (!existsSync(pkgPath)) {
    throw new Error('package.json not found. Run this from the project root.');
}

const pkg = JSON.parse(readFileSync(pkgPath, 'utf-8')) as {
    scripts?: Record<string, string>;
    engines?: { node?: string };
};

if (!existsSync(join(root, 'dist', 'server.js'))) {
    throw new Error('dist/server.js not found. Run "npm run build" first.');
}

function detectNodeMajor(): string {
    if (args.node) return args.node;

    // esbuild target in build.ts, e.g. target: 'node22'
    const buildTs = join(root, 'build.ts');
    if (existsSync(buildTs)) {
        const m = readFileSync(buildTs, 'utf-8').match(/target:\s*['"]node(\d+)['"]/);
        if (m) return m[1];
    }

    // engines.node, e.g. ">=22"
    const e = pkg.engines?.node?.match(/(\d+)/);
    if (e) return e[1];

    return '22';
}

const nodeMajor = detectNodeMajor();
const ubuntu = args.ubuntu as string;
const port = parseInt(args.port as string, 10);
const excludeSecrets = args['exclude-secrets'] as boolean;

if (!Number.isInteger(port) || port < 1 || port > 65535) {
    throw new Error(`Invalid --port: ${args.port}`);
}

const hasLock = existsSync(join(root, 'package-lock.json'));
const manifestFiles = hasLock ? 'package.json package-lock.json' : 'package.json';
const installProd = hasLock ? 'npm ci --omit=dev' : 'npm install --omit=dev';

// ------------------------------------------------------------
// Dockerfile
// ------------------------------------------------------------

const dockerfile = `# syntax=docker/dockerfile:1
# Generated by scripts/generate-dockerfile.ts - re-run the script instead of editing by hand.

ARG UBUNTU_VERSION=${ubuntu}
ARG NODE_MAJOR=${nodeMajor}

# ------------------------------------------------------------
# base: Ubuntu + Node.js (shared by every stage below)
# ------------------------------------------------------------
FROM ubuntu:\${UBUNTU_VERSION} AS base
ARG NODE_MAJOR
ENV DEBIAN_FRONTEND=noninteractive

RUN apt-get update \\
 && apt-get install -y --no-install-recommends ca-certificates curl gnupg \\
 && curl -fsSL https://deb.nodesource.com/setup_\${NODE_MAJOR}.x | bash - \\
 && apt-get install -y --no-install-recommends nodejs \\
 && apt-get purge -y --auto-remove curl gnupg \\
 && rm -rf /var/lib/apt/lists/*

WORKDIR /app

# ------------------------------------------------------------
# prod-deps: runtime dependencies only
# (esbuild is configured with packages: 'external', so dist/ needs node_modules)
# ------------------------------------------------------------
FROM base AS prod-deps

COPY ${manifestFiles} ./
RUN ${installProd} --ignore-scripts \\
 && npm cache clean --force

# ------------------------------------------------------------
# runtime: only what is needed to run the server
# ------------------------------------------------------------
FROM base AS runtime

ENV NODE_ENV=production \\
    DEPLOY_ENV=production \\
    PROD_PORT=${port}

RUN useradd --system --uid 10001 --user-group --no-create-home app

# package.json is required at runtime: its "type": "module" makes dist/*.js load as ESM
COPY --chown=app:app package.json ./
COPY --from=prod-deps --chown=app:app /app/node_modules ./node_modules
COPY --chown=app:app dist ./dist

# The server reads data/, keystore.json and .env relative to the working directory
WORKDIR /app/dist
USER app

EXPOSE ${port}

# TCP check: independent of auth, host validation and rate-limit middlewares
HEALTHCHECK --interval=30s --timeout=5s --start-period=15s --retries=3 \\
  CMD ["node", "-e", "const s=require('node:net').connect(Number(process.env.PROD_PORT),'127.0.0.1');s.on('connect',()=>process.exit(0));s.on('error',()=>process.exit(1))"]

# Node is PID 1 and handles SIGTERM itself (graceful shutdown in server.ts)
CMD ["node", "server.js"]
`;

// ------------------------------------------------------------
// .dockerignore
// ------------------------------------------------------------

const ignoreLines = [
    '# Generated by scripts/generate-dockerfile.ts',
    'node_modules',
    '.git',
    '.github',
    '.DS_Store',
    '*.log',
    'Dockerfile',
    '.dockerignore',
];

if (excludeSecrets) {
    ignoreLines.push('', '# Secrets: provide at runtime', 'dist/.env', 'dist/.env.*', 'dist/*.pem', 'dist/keystore*.json');
}

const dockerignore = ignoreLines.join('\n') + '\n';

// ------------------------------------------------------------
// Write files
// ------------------------------------------------------------

function write(name: string, content: string): void {
    const target = join(outDir, name);
    if (existsSync(target) && !args.force) {
        console.error(`✗ ${target} already exists (use --force to overwrite)`);
        process.exitCode = 1;
        return;
    }
    writeFileSync(target, content, 'utf-8');
    console.log(`✓ wrote ${target}`);
}

write('Dockerfile', dockerfile);
write('.dockerignore', dockerignore);

console.log(`\nNode ${nodeMajor} on ubuntu:${ubuntu}, listening on port ${port}\n`);
console.log('Build:  docker build -t api-server .   (uses the existing dist/)');
if (excludeSecrets) {
    console.log(
        `Run:    docker run -d -p ${port}:${port} --env-file .env \\\n` +
        '          -v "$PWD/keystore.json:/app/dist/keystore.json:ro" \\\n' +
        '          --stop-timeout 35 api-server',
    );
    console.log('\nNote: values in --env-file override the image defaults. Keep DEPLOY_ENV away from "local"\n(it switches to HTTPS with key.pem/cert.pem) and keep PROD_PORT in sync with -p.');
} else {
    console.log(`Run:    docker run -d -p ${port}:${port} --stop-timeout 35 api-server`);
    console.log('\nWARNING: dist/ contains .env, *.pem and keystore.json (copied by "npm run build"),');
    console.log('so they end up inside the image. Do not push it to a public registry.');
}